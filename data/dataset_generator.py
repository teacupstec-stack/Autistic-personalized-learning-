"""
Developmental pipeline test dataset generator for PUSG-Fusion (Component 1).

Provenance & Ethics Notice:
- Samples generated by this script are clearly labelled as 'synthetic_pipeline_validation'.
- Used exclusively for algorithmic pipeline verification, model training,
  and offline testing prior to institutional participant collection.
- Enrolment samples are strictly separated from train/val/test splits to prevent data leakage.
"""

import os
import sys
import json
import numpy as np
from typing import Dict, List, Any, Tuple

# Ensure project root is in sys.path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

from preprocessing.normalizer import GestureNormalizer

INTENTS = ["Help", "Break", "Finished", "Yes", "No"]
PARTICIPANTS = ["P001", "P002", "P003", "P004"]


def create_synthetic_gesture_trajectory(intent: str, time_steps: int = 32) -> Tuple[np.ndarray, np.ndarray]:
    """
    Synthesizes realistic 3D trajectories [32, 2, 21, 3] and masks [32, 2]
    reflecting the qualitative motion of the agreed intents.
    """
    t = np.linspace(0, 1, time_steps)
    lm = np.zeros((time_steps, 2, 21, 3), dtype=np.float32)
    masks = np.zeros((time_steps, 2), dtype=np.float32)

    # Hand shapes:
    # 1. Open hand template (fingers extended)
    open_hand = np.zeros((21, 3), dtype=np.float32)
    for i in range(1, 5): open_hand[i] = [0.08 + 0.04 * i, 0.15 + 0.04 * i, 0.0]  # thumb
    for i in range(5, 9): open_hand[i] = [0.04, 0.25 + 0.08 * (i - 5), 0.0]        # index
    for i in range(9, 13): open_hand[i] = [0.0, 0.30 + 0.08 * (i - 9), 0.0]        # middle
    for i in range(13, 17): open_hand[i] = [-0.04, 0.26 + 0.07 * (i - 13), 0.0]   # ring
    for i in range(17, 21): open_hand[i] = [-0.08, 0.20 + 0.06 * (i - 17), 0.0]   # pinky

    # 2. Fist template (fingers curled into palm)
    fist_hand = np.zeros((21, 3), dtype=np.float32)
    for i in range(1, 5): fist_hand[i] = [0.05 + 0.02 * i, 0.08, 0.04]             # thumb across
    for i in range(5, 9): fist_hand[i] = [0.03, 0.08 + 0.02 * (i - 5), -0.05]     # index curled
    for i in range(9, 13): fist_hand[i] = [0.0, 0.08 + 0.02 * (i - 9), -0.05]      # middle curled
    for i in range(13, 17): fist_hand[i] = [-0.03, 0.07 + 0.02 * (i - 13), -0.05] # ring curled
    for i in range(17, 21): fist_hand[i] = [-0.06, 0.06 + 0.02 * (i - 17), -0.05] # pinky curled

    # 3. Pointing / Wagging template (index extended, others curled)
    pointing_hand = fist_hand.copy()
    for i in range(5, 9): pointing_hand[i] = [0.03, 0.25 + 0.08 * (i - 5), 0.0]   # index extended

    if intent == "Help":
        # Right hand open palm raising upwards
        masks[:, 1] = 1.0
        wrist_y = 0.75 - 0.35 * (1.0 / (1.0 + np.exp(-8 * (t - 0.4))))
        wrist_x = 0.55 + 0.02 * np.sin(4 * np.pi * t)
        for step in range(time_steps):
            lm[step, 1, :, :] = open_hand + np.array([wrist_x[step], wrist_y[step], 0.0])

    elif intent == "Break":
        # Two open hands crossing inwards towards chest
        masks[:, 0] = 1.0  # Left
        masks[:, 1] = 1.0  # Right
        left_x = 0.35 + 0.16 * t
        right_x = 0.65 - 0.16 * t
        y_pos = 0.60 + 0.04 * np.sin(np.pi * t)
        for step in range(time_steps):
            lm[step, 0, :, :] = open_hand + np.array([left_x[step], y_pos[step], -0.05])
            lm[step, 1, :, :] = open_hand + np.array([right_x[step], y_pos[step], 0.05])

    elif intent == "Finished":
        # Both open hands sweeping outwards side-to-side
        masks[:, 0] = 1.0
        masks[:, 1] = 1.0
        left_x = 0.48 - 0.22 * np.sin(np.pi * t)
        right_x = 0.52 + 0.22 * np.sin(np.pi * t)
        y_pos = 0.55 - 0.08 * np.sin(np.pi * t)
        for step in range(time_steps):
            lm[step, 0, :, :] = open_hand + np.array([left_x[step], y_pos[step], 0.0])
            lm[step, 1, :, :] = open_hand + np.array([right_x[step], y_pos[step], 0.0])

    elif intent == "Yes":
        # Right hand fist pumping gently forward
        masks[:, 1] = 1.0
        wrist_z = -0.25 * np.sin(np.pi * t)
        wrist_y = 0.52 + 0.06 * np.sin(2 * np.pi * t)
        for step in range(time_steps):
            lm[step, 1, :, :] = fist_hand + np.array([0.55, wrist_y[step], wrist_z[step]])

    elif intent == "No":
        # Single hand pointing finger wagging horizontally
        masks[:, 1] = 1.0
        wrist_x = 0.55 + 0.16 * np.sin(4 * np.pi * t)
        wrist_y = 0.50 + 0.02 * np.cos(2 * np.pi * t)
        for step in range(time_steps):
            lm[step, 1, :, :] = pointing_hand + np.array([wrist_x[step], wrist_y[step], 0.0])

    # Add realistic sensor noise (Gaussian jitter std=0.008)
    jitter = np.random.normal(0, 0.008, lm.shape).astype(np.float32)
    # Only jitter valid hands
    for h in range(2):
        for s in range(time_steps):
            if masks[s, h] == 1.0:
                lm[s, h] += jitter[s, h]
            else:
                lm[s, h] = 0.0

    return lm, masks


def generate_pipeline_dataset(output_dir: str = "data/processed"):
    os.makedirs(output_dir, exist_ok=True)
    raw_dir = "data/d1_raw"
    os.makedirs(raw_dir, exist_ok=True)

    normalizer = GestureNormalizer(target_timesteps=32)

    all_samples = []
    enrolment_sample_ids = []
    train_sample_ids = []
    val_sample_ids = []
    test_sample_ids = []

    sample_counter = 0

    print("Generating synthetic pipeline validation dataset...")

    for pid in PARTICIPANTS:
        for intent in INTENTS:
            # 1. Generate 3 Enrolment samples per intent for this participant
            for enr_idx in range(3):
                sample_counter += 1
                sample_id = f"smp_enr_{pid}_{intent.lower()}_{enr_idx + 1}"
                lm, masks = create_synthetic_gesture_trajectory(intent)
                features = normalizer.normalize_spatial(lm, masks)

                sample_meta = {
                    "schema_version": "1.0.0",
                    "sample_id": sample_id,
                    "participant_id": pid,
                    "session_id": f"ses_enrolment_{pid}",
                    "activity_id": "counting_activity_01",
                    "confirmed_intent": intent,
                    "collection_source": "synthetic_pipeline_validation",
                    "is_enrolment": True,
                    "features": features.tolist(),
                    "num_frames": 32,
                    "sampling_rate_hz": 16.0,
                    "timestamps": np.linspace(0, 2000, 32).tolist(),
                    "handedness": ["Left", "Right"],
                    "tracking_validity_masks": masks.tolist(),
                }
                all_samples.append(sample_meta)
                enrolment_sample_ids.append(sample_id)

            # 2. Generate 12 test attempts across 3 sessions
            # Session 1 -> Train (6 samples)
            # Session 2 -> Val (3 samples)
            # Session 3 -> Test (3 samples)
            for attempt_idx in range(12):
                sample_counter += 1
                if attempt_idx < 6:
                    split_type = "train"
                    session_num = 1
                elif attempt_idx < 9:
                    split_type = "val"
                    session_num = 2
                else:
                    split_type = "test"
                    session_num = 3

                sample_id = f"smp_att_{pid}_{intent.lower()}_s{session_num}_{attempt_idx + 1}"
                lm, masks = create_synthetic_gesture_trajectory(intent)
                features = normalizer.normalize_spatial(lm, masks)

                sample_meta = {
                    "schema_version": "1.0.0",
                    "sample_id": sample_id,
                    "participant_id": pid,
                    "session_id": f"ses_{session_num:02d}_{pid}",
                    "activity_id": "counting_activity_01",
                    "confirmed_intent": intent,
                    "collection_source": "synthetic_pipeline_validation",
                    "is_enrolment": False,
                    "features": features.tolist(),
                    "num_frames": 32,
                    "sampling_rate_hz": 16.0,
                    "timestamps": np.linspace(0, 2000, 32).tolist(),
                    "handedness": ["Left", "Right"],
                    "tracking_validity_masks": masks.tolist(),
                }
                all_samples.append(sample_meta)

                if split_type == "train":
                    train_sample_ids.append(sample_id)
                elif split_type == "val":
                    val_sample_ids.append(sample_id)
                else:
                    test_sample_ids.append(sample_id)

    # Save full dataset file
    dataset_file = os.path.join(output_dir, "d1_synthetic_dataset.json")
    with open(dataset_file, "w") as f:
        json.dump(all_samples, f, indent=2)

    # Save split manifest
    manifest = {
        "dataset_name": "D1_Synthetic_Pipeline_Validation",
        "description": "Synthetic dataset for algorithmic pipeline verification. Enrolment strictly separated from evaluation.",
        "schema_version": "1.0.0",
        "intents": INTENTS,
        "participants": PARTICIPANTS,
        "counts": {
            "total_samples": len(all_samples),
            "enrolment": len(enrolment_sample_ids),
            "train": len(train_sample_ids),
            "val": len(val_sample_ids),
            "test": len(test_sample_ids),
        },
        "splits": {
            "enrolment": enrolment_sample_ids,
            "train": train_sample_ids,
            "val": val_sample_ids,
            "test": test_sample_ids,
        }
    }
    manifest_file = os.path.join(output_dir, "split_manifest.json")
    with open(manifest_file, "w") as f:
        json.dump(manifest, f, indent=2)

    print(f"Generated {len(all_samples)} total samples:")
    print(f"  - Enrolment: {len(enrolment_sample_ids)}")
    print(f"  - Train:     {len(train_sample_ids)}")
    print(f"  - Val:       {len(val_sample_ids)}")
    print(f"  - Test:      {len(test_sample_ids)}")
    print(f"Saved dataset to {dataset_file}")
    print(f"Saved split manifest to {manifest_file}")
    return manifest


if __name__ == "__main__":
    generate_pipeline_dataset()
